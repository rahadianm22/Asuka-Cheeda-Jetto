export function translate(key, lang) {
  return (I18N[key] && I18N[key][lang]) || key;
}

export function translateVars(key, lang, vars) {
  let str = translate(key, lang);
  for (const k in vars) str = str.replace(`{${k}}`, vars[k]);
  return str;
}
